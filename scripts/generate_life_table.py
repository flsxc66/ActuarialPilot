def _interpolate(table: dict[int, float]) -> dict:
    """线性插值填充缺失年龄，最大到 120。"""
    full = {}
    ages = sorted(table.keys())
    for age in range(ages[0], ages[-1] + 1):
        # 找到相邻已知年龄
        lower = max((a for a in ages if a <= age), default=ages[0])
        upper = min((a for a in ages if a >= age), default=ages[-1])
        if lower == upper:
            full[age] = table[lower]
        else:
            w = (age - lower) / (upper - lower)
            full[age] = table[lower] * (1 - w) + table[upper] * w
    return full


def write_table(sex: str, table: dict[int, float], path: Path) -> None:
    """写入 CSV：age, sex, qx。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    full = _interpolate(table)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["age", "sex", "qx"])
        for age in range(min(full), max(full) + 1):
            writer.writerow([age, sex, f"{full[age]:.6f}"])


